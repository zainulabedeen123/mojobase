#!/usr/bin/env python3
"""Renders deploy/platform/docker-compose.yml with the Caddyfile inlined.

Hostinger's Docker Manager (and other compose-only hosts) can't bind-mount files
from a checkout, so Caddy writes its config from the compose file at start-up.
Usage: render-compose.py [image-tag]   (default: ${MOJOBASE_TAG} placeholder)
"""
import pathlib
import sys

here = pathlib.Path(__file__).parent
tag = sys.argv[1] if len(sys.argv) > 1 else '${MOJOBASE_TAG:?set MOJOBASE_TAG}'
caddy = (here / 'Caddyfile').read_text()
indented = ''.join('        ' + line if line.strip() else '\n' for line in caddy.splitlines(True))
image = lambda name: f'ghcr.io/zainulabedeen123/{name}:{tag}'

print(f'''# Generated by render-compose.py from Caddyfile - edit those, not this file.
services:
  caddy:
    image: caddy:2.8.4-alpine
    restart: unless-stopped
    command:
      - sh
      - -c
      - |
        cat > /etc/caddy/Caddyfile <<'CADDY'
{indented}        CADDY
        exec caddy run --config /etc/caddy/Caddyfile --adapter caddyfile
    ports:
      - "80:80"
      - "443:443"
      - "443:443/udp"
    volumes:
      - caddy-data:/data
      - caddy-config:/config
    networks:
      - edge
    depends_on:
      - console

  console:
    image: {image('mojobase-console')}
    restart: unless-stopped
    # Secrets (CONSOLE_SECRET, RESEND_API_KEY, GOOGLE_DRIVE_CLIENT_ID/SECRET) live on the
    # server only, so deploys never carry them.
    env_file: /opt/mojobase/platform.env
    environment:
      EMAIL_FROM: Mojobase <no-reply@mojobase.dev>
      # Platform admins (set in the project's .env in Docker Manager, not here).
      ADMIN_EMAILS: ${{ADMIN_EMAILS:-}}
      CONSOLE_ORIGIN: https://mojobase.dev
      BASE_DOMAIN: mojobase.dev
      DB_HOST: db.mojobase.dev
      PROJECT_APP_IMAGE: {image('mojobase')}
      PROJECT_POSTGRES_IMAGE: {image('mojobase-postgres')}
      PROJECT_DENO_IMAGE: {image('mojobase-deno')}
      EDGE_NETWORK: mojobase-edge
      CADDY_DATA_VOLUME: mojobase-caddy-data
      COMPOSE_ROOT: /docker
      DB_PORT_MIN: "15400"
      DB_PORT_MAX: "15499"
      MAX_PROJECTS: "8"
      MAX_PROJECTS_PER_USER: "2"
      BACKUP_HOUR_UTC: "3"
      BACKUP_KEEP: "7"
      # Recorded in every offsite backup's manifest.
      MOJOBASE_VERSION: {tag}
    volumes:
      - console-data:/data
      - caddy-data:/caddy-data:ro
      - /var/run/docker.sock:/var/run/docker.sock
      # Project compose files live in the host's /docker/mb-<ref>/ (same path inside),
      # where hPanel's Docker Manager lists projects.
      - /docker:/docker
    networks:
      - edge

volumes:
  caddy-data:
    name: mojobase-caddy-data
  caddy-config:
    name: mojobase-caddy-config
  console-data:
    name: mojobase-console-data

networks:
  edge:
    external: true
    name: mojobase-edge
''', end='')
